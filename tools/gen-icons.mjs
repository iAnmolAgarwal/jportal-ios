// android vector drawables -> src/ui/icons.js (path data only, fill = currentColor)
import fs from 'node:fs';
import path from 'node:path';
const dir = process.argv[2];
const out = {};
for (const f of fs.readdirSync(dir).filter((f) => /^ic_.*\.xml$/.test(f) && !/launcher/.test(f))) {
  const x = fs.readFileSync(path.join(dir, f), 'utf8');
  const vw = /viewportWidth="([\d.]+)"/.exec(x)?.[1] || '24';
  const vh = /viewportHeight="([\d.]+)"/.exec(x)?.[1] || '24';
  const paths = [...x.matchAll(/android:pathData="([^"]+)"/g)].map((m) => m[1]);
  const ty = Number(/translateY="(-?[\d.]+)"/.exec(x)?.[1] || 0);
  if (paths.length) out[f.slice(3, -4)] = { vb: `0 ${-ty} ${vw} ${vh}`, d: paths };
}
fs.writeFileSync('src/ui/icons.js', `// generated by tools/gen-icons.mjs from jportal-android's res/drawable (material symbols)\nexport const ICONS = ${JSON.stringify(out, null, 0).replace(/\},"/g, '},\n"')};\n`);
console.log(Object.keys(out).join(' '));
